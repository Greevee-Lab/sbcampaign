//! Sign-in tickets from an identity provider (steelcore concept, trust model).
//!
//! The campaign server does not trust the XUID a game reports and has no
//! connection to the provider's account database. Instead the provider
//! (steelnet, for Steelbound players) issues a short-lived ticket after its
//! normal sign-in, signed with Ed25519. This module checks such a ticket with
//! the provider's **public** keys and returns the identity
//! `(provider, external_id)` for [`CampaignCore::resolve_identity`].
//!
//! A ticket may be presented several times while it is valid: every campaign
//! transaction of the game is its own short TCP connection.
//!
//! # Wire format v1
//!
//! Binary, big-endian. The signature covers every byte before it.
//!
//! | offset | size | field |
//! |---|---|---|
//! | 0 | 4 | magic `SBCT` |
//! | 4 | 1 | version = 1 |
//! | 5 | 8 | key id = first 8 bytes of the Ed25519 public key |
//! | 13 | 8 | issued at (unix seconds) |
//! | 21 | 8 | expires at (unix seconds) |
//! | 29 | 4 | account id (1 ..= 2^32-1) |
//! | 33 | 8 | pseudo-XUID `0x53424C01_<account id>` |
//! | 41 | 16 | ticket id (random) |
//! | 57 | 1+n | issuer (`[a-z0-9.-]`, 1..=32 bytes) |
//! | | 1+n | provider (same alphabet) |
//! | | 1+n | campaign id (same alphabet) |
//! | | 1+n | display name (UTF-8, 1..=64 bytes) |
//! | end | 64 | Ed25519 signature (RFC 8032) |
//!
//! Checks, in this order (the first failing one is reported): structure,
//! version, known key id, signature, issuer, provider, campaign, identity
//! (pseudo-XUID matches the account id), lifetime (positive, at most
//! `max_lifetime`), not yet valid / expired with `max_clock_skew` tolerance.
//! The shared test vectors in `testdata/campaign_ticket_vectors.toml` are
//! generated by the issuer and must pass here unchanged.
//!
//! [`CampaignCore::resolve_identity`]: crate::core_api::CampaignCore::resolve_identity
#![allow(dead_code)] // Used by the Steelbound gateway, which is the next step.

#[cfg(test)]
mod tests;

use crate::core_api::{Provider, STEELBOUND_XUID_PREFIX};
use ed25519_dalek::{Signature, VerifyingKey};
use std::{
    fmt,
    time::{SystemTime, UNIX_EPOCH},
};
use thiserror::Error;

pub const MAGIC: &[u8; 4] = b"SBCT";
pub const VERSION: u8 = 1;
pub const KEY_ID_LEN: usize = 8;
pub const SIGNATURE_LEN: usize = 64;
const HEADER_LEN: usize = 57;
const MAX_LABEL: usize = 32;
const MAX_NAME: usize = 64;
/// Largest possible v1 ticket.
pub const MAX_TICKET_LEN: usize = HEADER_LEN + 3 * (1 + MAX_LABEL) + 1 + MAX_NAME + SIGNATURE_LEN;
/// Default tolerance for clock differences between issuer and verifier.
pub const DEFAULT_MAX_CLOCK_SKEW: u64 = 60;
/// Default upper bound for `expires_at - issued_at`.
pub const DEFAULT_MAX_LIFETIME: u64 = 3600;

/// Why a ticket was refused. [`TicketError::code`] matches the `result`
/// strings of the shared test vectors.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum TicketError {
    #[error("malformed ticket")]
    Malformed,
    #[error("unsupported ticket version")]
    UnsupportedVersion,
    #[error("ticket signed with an unknown key")]
    UnknownKey,
    #[error("bad ticket signature")]
    BadSignature,
    #[error("ticket from another issuer")]
    WrongIssuer,
    #[error("ticket for an unsupported provider")]
    WrongProvider,
    #[error("ticket for another campaign")]
    WrongCampaign,
    #[error("inconsistent identity in ticket")]
    BadIdentity,
    #[error("ticket lifetime out of range")]
    BadLifetime,
    #[error("ticket not yet valid")]
    NotYetValid,
    #[error("ticket expired")]
    Expired,
}

impl TicketError {
    pub fn code(self) -> &'static str {
        match self {
            TicketError::Malformed => "malformed",
            TicketError::UnsupportedVersion => "unsupported_version",
            TicketError::UnknownKey => "unknown_key",
            TicketError::BadSignature => "bad_signature",
            TicketError::WrongIssuer => "wrong_issuer",
            TicketError::WrongProvider => "wrong_provider",
            TicketError::WrongCampaign => "wrong_campaign",
            TicketError::BadIdentity => "bad_identity",
            TicketError::BadLifetime => "bad_lifetime",
            TicketError::NotYetValid => "not_yet_valid",
            TicketError::Expired => "expired",
        }
    }
}

/// Error in the `[ticket]` configuration section.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
#[error("[ticket] configuration: {0}")]
pub struct TicketConfigError(String);

/// Verifier settings: the `[ticket]` section of the server configuration
/// (`/etc/steelcore/steelcore.toml`).
///
/// ```toml
/// [ticket]
/// issuer = "steelnet-eu"
/// campaign = "steelbound-s1"
/// # Public keys of the issuer, 64 hex digits each. Several keys = rotation.
/// public_keys = ["…"]
/// max_clock_skew = 60   # optional, seconds
/// max_lifetime = 3600   # optional, seconds
/// ```
#[derive(Clone)]
pub struct TicketConfig {
    pub issuer: String,
    pub campaign: String,
    pub max_clock_skew: u64,
    pub max_lifetime: u64,
    keys: Vec<VerifyingKey>,
}

impl fmt::Debug for TicketConfig {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("TicketConfig")
            .field("issuer", &self.issuer)
            .field("campaign", &self.campaign)
            .field("max_clock_skew", &self.max_clock_skew)
            .field("max_lifetime", &self.max_lifetime)
            .field("key_ids", &self.key_ids())
            .finish()
    }
}

fn valid_label(s: &str) -> bool {
    (1..=MAX_LABEL).contains(&s.len())
        && s.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'.' || b == b'-')
}

fn parse_hex32(s: &str) -> Option<[u8; 32]> {
    let s = s.trim();
    if s.len() != 64 || !s.is_ascii() {
        return None;
    }
    let mut out = [0u8; 32];
    for (i, byte) in out.iter_mut().enumerate() {
        *byte = u8::from_str_radix(&s[2 * i..2 * i + 2], 16).ok()?;
    }
    Some(out)
}

impl TicketConfig {
    pub fn new(
        issuer: &str,
        campaign: &str,
        public_keys: &[[u8; 32]],
        max_clock_skew: u64,
        max_lifetime: u64,
    ) -> Result<Self, TicketConfigError> {
        let err = |m: &str| Err(TicketConfigError(m.to_string()));
        if !valid_label(issuer) {
            return err("issuer must be 1-32 of a-z 0-9 . -");
        }
        if !valid_label(campaign) {
            return err("campaign must be 1-32 of a-z 0-9 . -");
        }
        if public_keys.is_empty() {
            return err("public_keys is empty");
        }
        if max_clock_skew > 600 {
            return err("max_clock_skew above 600 s");
        }
        if !(1..=86_400).contains(&max_lifetime) {
            return err("max_lifetime must be 1..=86400 s");
        }
        let mut keys: Vec<VerifyingKey> = Vec::new();
        for raw in public_keys {
            let key = VerifyingKey::from_bytes(raw).map_err(|_| TicketConfigError("invalid public key".into()))?;
            // Small-order keys would let anyone sign; refuse them outright.
            if key.is_weak() {
                return err("weak public key");
            }
            if keys.iter().any(|k| k.as_bytes()[..KEY_ID_LEN] == raw[..KEY_ID_LEN]) {
                return err("two public keys share a key id");
            }
            keys.push(key);
        }
        Ok(TicketConfig {
            issuer: issuer.to_string(),
            campaign: campaign.to_string(),
            max_clock_skew,
            max_lifetime,
            keys,
        })
    }

    /// Read the `[ticket]` section of a configuration table. `Ok(None)` when
    /// the section is missing (no ticket sign-in on this instance).
    pub fn from_toml(config: &toml::Table) -> Result<Option<Self>, TicketConfigError> {
        let Some(section) = config.get("ticket") else {
            return Ok(None);
        };
        let section = section
            .as_table()
            .ok_or_else(|| TicketConfigError("not a table".into()))?;
        let text = |name: &str| {
            section
                .get(name)
                .and_then(|v| v.as_str())
                .ok_or_else(|| TicketConfigError(format!("{name} missing")))
        };
        let seconds = |name: &str, default: u64| match section.get(name) {
            None => Ok(default),
            Some(v) => v
                .as_integer()
                .and_then(|n| u64::try_from(n).ok())
                .ok_or_else(|| TicketConfigError(format!("{name} must be a non-negative integer"))),
        };
        let keys = section
            .get("public_keys")
            .and_then(|v| v.as_array())
            .ok_or_else(|| TicketConfigError("public_keys missing".into()))?
            .iter()
            .map(|v| {
                v.as_str()
                    .and_then(parse_hex32)
                    .ok_or_else(|| TicketConfigError("public_keys: 64 hex digits each".into()))
            })
            .collect::<Result<Vec<_>, _>>()?;
        TicketConfig::new(
            text("issuer")?,
            text("campaign")?,
            &keys,
            seconds("max_clock_skew", DEFAULT_MAX_CLOCK_SKEW)?,
            seconds("max_lifetime", DEFAULT_MAX_LIFETIME)?,
        )
        .map(Some)
    }

    /// Key ids (hex) of the configured keys, for logs.
    pub fn key_ids(&self) -> Vec<String> {
        self.keys
            .iter()
            .map(|k| k.as_bytes()[..KEY_ID_LEN].iter().map(|b| format!("{b:02x}")).collect())
            .collect()
    }
}

/// A verified ticket.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Ticket {
    pub key_id: [u8; KEY_ID_LEN],
    pub issued_at: u64,
    pub expires_at: u64,
    pub account: u32,
    pub xuid: u64,
    pub ticket_id: [u8; 16],
    pub issuer: String,
    pub provider: Provider,
    pub campaign: String,
    /// Display name chosen by the player at the provider (not an identity).
    pub display_name: String,
}

impl Ticket {
    /// `(provider, external_id)` for `resolve_identity`.
    pub fn identity(&self) -> (Provider, String) {
        (self.provider, self.account.to_string())
    }
}

struct Reader<'a> {
    buf: &'a [u8],
    pos: usize,
}

impl<'a> Reader<'a> {
    fn take(&mut self, n: usize) -> Result<&'a [u8], TicketError> {
        let end = self.pos.checked_add(n).ok_or(TicketError::Malformed)?;
        let out = self.buf.get(self.pos..end).ok_or(TicketError::Malformed)?;
        self.pos = end;
        Ok(out)
    }
    fn array<const N: usize>(&mut self) -> Result<[u8; N], TicketError> {
        Ok(self.take(N)?.try_into().unwrap())
    }
    fn text(&mut self, max: usize) -> Result<&'a [u8], TicketError> {
        let n = self.take(1)?[0] as usize;
        if n == 0 || n > max {
            return Err(TicketError::Malformed);
        }
        self.take(n)
    }
    fn label(&mut self) -> Result<String, TicketError> {
        let raw = self.text(MAX_LABEL)?;
        let s = std::str::from_utf8(raw).map_err(|_| TicketError::Malformed)?;
        if !valid_label(s) {
            return Err(TicketError::Malformed);
        }
        Ok(s.to_string())
    }
}

/// Verify a ticket at time `now` (unix seconds).
pub fn verify_at(ticket: &[u8], config: &TicketConfig, now: u64) -> Result<Ticket, TicketError> {
    if ticket.len() < HEADER_LEN + 4 + SIGNATURE_LEN || ticket.len() > MAX_TICKET_LEN {
        return Err(TicketError::Malformed);
    }
    let (signed, signature) = ticket.split_at(ticket.len() - SIGNATURE_LEN);
    let mut r = Reader { buf: signed, pos: 0 };
    if r.take(4)? != MAGIC {
        return Err(TicketError::Malformed);
    }
    if r.take(1)?[0] != VERSION {
        return Err(TicketError::UnsupportedVersion);
    }
    let key_id: [u8; KEY_ID_LEN] = r.array()?;
    let issued_at = u64::from_be_bytes(r.array()?);
    let expires_at = u64::from_be_bytes(r.array()?);
    let account = u32::from_be_bytes(r.array()?);
    let xuid = u64::from_be_bytes(r.array()?);
    let ticket_id: [u8; 16] = r.array()?;
    let issuer = r.label()?;
    let provider = r.label()?;
    let campaign = r.label()?;
    let display_name = std::str::from_utf8(r.text(MAX_NAME)?)
        .map_err(|_| TicketError::Malformed)?
        .to_string();
    if r.pos != signed.len() {
        return Err(TicketError::Malformed);
    }

    let key = config
        .keys
        .iter()
        .find(|k| k.as_bytes()[..KEY_ID_LEN] == key_id)
        .ok_or(TicketError::UnknownKey)?;
    let signature = Signature::from_slice(signature).map_err(|_| TicketError::BadSignature)?;
    // Strict: canonical S, no small-order R or key (no malleable signatures).
    key.verify_strict(signed, &signature)
        .map_err(|_| TicketError::BadSignature)?;

    if issuer != config.issuer {
        return Err(TicketError::WrongIssuer);
    }
    // Only Steelbound tickets exist today; other providers have their own gateway.
    let provider = match Provider::from_id(&provider) {
        Some(p @ Provider::Steelbound) => p,
        _ => return Err(TicketError::WrongProvider),
    };
    if campaign != config.campaign {
        return Err(TicketError::WrongCampaign);
    }
    if account == 0 || xuid != (u64::from(STEELBOUND_XUID_PREFIX) << 32 | u64::from(account)) {
        return Err(TicketError::BadIdentity);
    }
    if expires_at <= issued_at || expires_at - issued_at > config.max_lifetime {
        return Err(TicketError::BadLifetime);
    }
    if now.saturating_add(config.max_clock_skew) < issued_at {
        return Err(TicketError::NotYetValid);
    }
    if now >= expires_at.saturating_add(config.max_clock_skew) {
        return Err(TicketError::Expired);
    }
    Ok(Ticket {
        key_id,
        issued_at,
        expires_at,
        account,
        xuid,
        ticket_id,
        issuer,
        provider,
        campaign,
        display_name,
    })
}

/// Verify a ticket against the current system time.
pub fn verify(ticket: &[u8], config: &TicketConfig) -> Result<Ticket, TicketError> {
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    verify_at(ticket, config, now)
}
